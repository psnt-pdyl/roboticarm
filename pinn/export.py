"""Export the motion PINN and the arm's physics as ../pinn-weights.js.

The page computes motor torques with the same masses, inertias and limits, so its
torque readout matches what the network was trained against.
"""
import base64
import json
from pathlib import Path

import numpy as np
import torch

import dynamics as dy
from model import T_REF
from train import T_MIN

HERE = Path(__file__).parent
OUT = HERE.parent / "pinn-weights.js"


def main():
    ck = torch.load(HERE / "pinn.pt", map_location="cpu")
    tensors = {}
    for name, t in ck["state"].items():
        arr = np.ascontiguousarray(t.float().numpy().astype("<f4"))
        tensors[name] = {"shape": list(arr.shape), "b64": base64.b64encode(arr.tobytes()).decode()}
    physics = {"g": dy.G, "len": dy.LEN.tolist(), "mass": dy.MASS.tolist(), "com": dy.COM.tolist(),
               "inertia": dy.INERTIA.tolist(), "tau_max": dy.TAU_MAX.tolist(), "part_mass": dy.PART_MASS,
               "t_ref": T_REF, "t_min": T_MIN}
    payload = {"layers": ck["layers"], "tensors": tensors, "physics": physics}
    evp = HERE / "eval.json"
    if evp.exists():
        r = json.loads(evp.read_text())["random_moves"]
        payload["eval"] = {"effort_vs_blend_pct": r["pinn"]["effort_vs_blend_pct"],
                           "gap_to_optimum_pct": r["pinn_gap_to_optimum_pct"]}
    OUT.write_text("// Trained motion PINN and arm physics (generated by pinn/export.py)\nwindow.MOTION_PINN = "
                   + json.dumps(payload, separators=(",", ":")) + ";\n")
    n = sum(int(np.prod(v["shape"])) for v in tensors.values())
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e6:.2f} MB, {n:,} values)")


if __name__ == "__main__":
    main()
