"""Export a motion PINN and the arm's physics as a script the web pages load.

    python export.py                                   # pinn.pt -> ../pinn-weights.js (window.MOTION_PINN)
    python export.py --model model_1kg --out ../pinn-1kg-weights.js --name MOTION_PINN_1KG

The pages compute motor torques with the same masses, inertias and limits, so their
torque readouts match what the network was trained against. payload_max is the
payload range the model was trained on.
"""
import argparse
import base64
import json
from pathlib import Path

import numpy as np
import torch

import dynamics as dy
from model import T_REF
from train import T_MIN

HERE = Path(__file__).parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=".", help="folder holding pinn.pt and eval.json")
    ap.add_argument("--out", default=str(HERE.parent / "pinn-weights.js"))
    ap.add_argument("--name", default="MOTION_PINN", help="global the page reads")
    ap.add_argument("--payload-max", type=float, default=None, help="training payload range, kg (default: from eval.json)")
    args = ap.parse_args()

    src, out = HERE / args.model, Path(args.out)
    ck = torch.load(src / "pinn.pt", map_location="cpu")
    tensors = {}
    for name, t in ck["state"].items():
        arr = np.ascontiguousarray(t.float().numpy().astype("<f4"))
        tensors[name] = {"shape": list(arr.shape), "b64": base64.b64encode(arr.tobytes()).decode()}
    ev = json.loads((src / "eval.json").read_text()) if (src / "eval.json").exists() else None
    payload_max = args.payload_max if args.payload_max is not None else dy.PAYLOAD_MAX
    physics = {"g": dy.G, "len": dy.LEN.tolist(), "mass": dy.MASS.tolist(), "com": dy.COM.tolist(),
               "inertia": dy.INERTIA.tolist(), "tau_max": dy.TAU_MAX.tolist(), "part_mass": dy.PART_MASS,
               "payload_max": payload_max, "t_ref": T_REF, "t_min": T_MIN}
    payload = {"layers": ck["layers"], "tensors": tensors, "physics": physics}
    if ev:
        r = ev["random_moves"]
        payload["eval"] = {"effort_vs_blend_pct": r["pinn"]["effort_vs_blend_pct"],
                           "gap_to_optimum_pct": r["pinn_gap_to_optimum_pct"]}
    out.write_text(f"// Trained motion PINN and arm physics (generated by pinn/export.py from {args.model})\n"
                   f"window.{args.name} = " + json.dumps(payload, separators=(",", ":")) + ";\n")
    n = sum(int(np.prod(v["shape"])) for v in tensors.values())
    print(f"wrote {out} ({out.stat().st_size / 1e6:.2f} MB, {n:,} values, trained payload 0-{payload_max:g} kg)")


if __name__ == "__main__":
    main()
