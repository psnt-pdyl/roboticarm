"""Export the trained network and the camera definition as ../vision-weights.js.

The page reads the camera constants from this file too, so its camera image always
matches the one the network was trained on.
"""
import base64
import json
from pathlib import Path

import numpy as np
import torch

import scene
from model import POOL_AFTER

HERE = Path(__file__).parent
OUT = HERE.parent / "vision-weights.js"


def main():
    ck = torch.load(HERE / "vision_net.pt", map_location="cpu")
    tensors = {}
    for name, t in ck["state"].items():
        arr = np.ascontiguousarray(t.float().numpy().astype("<f4"))
        tensors[name] = {"shape": list(arr.shape), "b64": base64.b64encode(arr.tobytes()).decode()}
    camera = {"x0": scene.X0, "x1": scene.X1, "z0": scene.Z0, "z1": scene.Z1, "w": scene.W, "h": scene.H,
              "ss": scene.SS, "part": scene.BS, "colors": scene.COLORS, "radii": scene.RADII}
    payload = {"tensors": tensors, "camera": camera, "pool_after": list(POOL_AFTER)}
    evp = HERE / "eval.json"
    if evp.exists():
        payload["eval"] = json.loads(evp.read_text())["clean"]
    OUT.write_text("// Trained part-finding network and camera definition (generated by vision/export.py)\n"
                   "window.VISION_NET = " + json.dumps(payload, separators=(",", ":")) + ";\n")
    n = sum(int(np.prod(v["shape"])) for v in tensors.values())
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e3:.0f} kB, {n:,} values)")


if __name__ == "__main__":
    main()
