"""Export the trained weights for the web page as ../ik-gnn-weights.js.

Each tensor is stored as base64 float32 so the page can run the same forward pass
in plain JavaScript with no ML library.
"""
import base64
import json
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).parent
OUT = HERE.parent / "ik-gnn-weights.js"


def main():
    ck = torch.load(HERE / "ik_gnn.pt", map_location="cpu")
    tensors = {}
    for name, t in ck["state"].items():
        if t.dtype != torch.float32:
            t = t.float()
        arr = np.ascontiguousarray(t.numpy().astype("<f4"))
        tensors[name] = {"shape": list(arr.shape), "b64": base64.b64encode(arr.tobytes()).decode()}
    payload = {"hidden": ck["hidden"], "steps": ck["steps"], "tensors": tensors}
    evp = HERE / "eval.json"
    if evp.exists():
        ev = json.loads(evp.read_text())
        payload["eval"] = {"tcp_err_mm": ev["random_targets"]["tcp_err_mm"],
                           "within_2mm_pct": ev["random_targets"]["within_2mm_pct"]}
    OUT.write_text("// Trained IK graph network weights (generated by gnn/export.py)\nwindow.IK_GNN = "
                   + json.dumps(payload, separators=(",", ":")) + ";\n")
    n = sum(int(np.prod(v["shape"])) for v in tensors.values())
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e6:.2f} MB, {n:,} values)")


if __name__ == "__main__":
    main()
